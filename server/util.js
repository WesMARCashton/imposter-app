const crypto = require('crypto');

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function genId() {
  return crypto.randomBytes(8).toString('hex');
}

module.exports = { shuffle, genId };
